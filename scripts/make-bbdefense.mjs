// Computes the pub chart's deep/mid BB defense vs each opener: src/data/sets/pubBbDefense.ts.
// Usage: node scripts/make-bbdefense.mjs   (seconds; reuses the cached equity table)
//
// For each opener seat, against that seat's pub open range:
//   call    if  realized equity  (raw equity x realization) >= the pot odds of the call
//   3-bet   if  raw equity >= VALUE_EQUITY or QQ+/AK (value), plus suited wheel aces half the time vs later seats
import { writeFileSync } from "node:fs";
import { load, loadEquityTable } from "./equity-cache.mjs";

const root = new URL("..", import.meta.url).pathname;
const VALUE_EQUITY = Number(process.env.VALUE_EQUITY ?? 0.6);
const STAGES = { deep: 3, mid: 2.5 }; // open size per pub stage
const OPENERS = ["UTG", "UTG+1", "UTG+2", "LJ", "HJ", "CO", "BTN", "SB"];
// Always value 3-bets, whatever the opener: AK has the blockers and plays well against calls.
const VALUE_FLOOR = ["AA", "KK", "QQ", "AKs", "AKo"];
const BLUFFS = { HJ: ["A5s", "A4s"], CO: ["A5s", "A4s", "A3s"], BTN: ["A5s", "A4s", "A3s", "A2s"], SB: ["A5s", "A4s", "A3s", "A2s"] };

const { getSet } = await load("src/data/charts.ts");
const { ALL_HANDS, comboCount } = await load("src/poker/cards.ts");
const { rangeToString } = await load("src/poker/range.ts");
const { baseRealization } = await load("src/poker/realization.ts");
const { eq, cnt } = await loadEquityTable();
const N = ALL_HANDS.length;
const pub = getSet("pub");
const pct = (r) => ALL_HANDS.reduce((s, h) => s + (r[h] ?? 0) * comboCount(h), 0) / 13.26;

const out = {};
for (const [stageId, open] of Object.entries(STAGES)) {
  const stage = pub.stages.find((s) => s.id === stageId);
  out[stageId] = {};
  const rows = [];
  for (const opener of OPENERS) {
    const rfi = stage.scenarios.find((s) => s.kind === "rfi" && s.hero === opener);
    const w = ALL_HANDS.map((h) => 1 - rfi.strategy[h].fold); // how often the opener opens each hand
    // Pot after my call: both opens, the ante, and the SB's dead blind unless the SB opened.
    const finalPot = 2 * open + 1 + (opener === "SB" ? 0 : 0.5);
    const need = (open - 1) / finalPot;
    const threeBet = {}, call = {};
    for (let x = 0; x < N; x++) {
      let m = 0, e = 0;
      for (let h = 0; h < N; h++) {
        const k = cnt[x * N + h] * w[h];
        m += k;
        e += k * eq[x * N + h];
      }
      const equity = e / m, hand = ALL_HANDS[x];
      if (equity >= VALUE_EQUITY || VALUE_FLOOR.includes(hand)) threeBet[hand] = 1;
      else if ((BLUFFS[opener] ?? []).includes(hand)) threeBet[hand] = 0.5;
      if (equity * baseRealization(hand) >= need) call[hand] = 1;
    }
    out[stageId][opener] = { threeBet: rangeToString(threeBet), call: rangeToString(call) };
    const callOnly = Object.fromEntries(ALL_HANDS.map((h) => [h, Math.min(call[h] ?? 0, 1 - (threeBet[h] ?? 0))]));
    rows.push(`${opener} 3bet ${pct(threeBet).toFixed(0)}% call ${pct(callOnly).toFixed(0)}% (need ${(need * 100).toFixed(0)}%)`);
  }
  console.log(`${stageId} (${open}bb open): ${rows.join(" | ")}`);
}

writeFileSync(
  root + "src/data/sets/pubBbDefense.ts",
  `// Generated by scripts/make-bbdefense.mjs. Do not edit by hand; rerun the script instead.
// BB defense vs each opener for the pub deep/mid stages, against that seat's pub open range:
// call when equity x realization (src/poker/realization.ts) beats the pot odds; 3-bet when raw
// equity >= ${VALUE_EQUITY} or QQ+/AK, plus suited wheel aces half the time against later seats.

export const PUB_BB_DEFENSE: Record<"deep" | "mid", Record<string, { threeBet: string; call: string }>> = ${JSON.stringify(out, null, 2)};
`,
);
console.log("wrote src/data/sets/pubBbDefense.ts");
