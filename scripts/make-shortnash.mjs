// Computes the short-stack open / re-jam charts in src/data/sets/shortNashData.ts.
// Usage: node scripts/make-shortnash.mjs   (a few minutes; reuses the cached equity table)
import { writeFileSync } from "node:fs";
import { cpus } from "node:os";
import { isMainThread, parentPort, Worker, workerData } from "node:worker_threads";
import { load, loadEquityTable } from "./equity-cache.mjs";

const root = new URL("..", import.meta.url).pathname;
const STACKS = [10, 12, 15, 17, 20, 25];
const SEATS = ["UTG", "UTG+1", "UTG+2", "LJ", "HJ", "CO", "BTN", "SB", "BB"];
const OPEN = 2;
const ITERATIONS = 3000;
const RANKS = "23456789TJQKA";

/**
 * Share of its equity the BB realizes after flatting an open out of position, before the stack
 * adjustment: pairs and connected or broadway suited hands play well; weak offsuit hands get
 * bet off their equity.
 */
function baseRealization(h) {
  if (h.length === 2) return 0.9;
  const hi = RANKS.indexOf(h[0]), lo = RANKS.indexOf(h[1]);
  const gap = hi - lo - 1;
  const broadway = lo >= RANKS.indexOf("T");
  if (h[2] === "s") return broadway || gap <= 1 ? 0.9 : hi >= RANKS.indexOf("Q") || gap <= 2 ? 0.8 : 0.65;
  return broadway ? 0.85 : hi === 12 || (gap <= 1 && lo >= RANKS.indexOf("5")) ? 0.72 : 0.55;
}
/** Shorter stacks leave less to play after the flop, so the shortfall shrinks (full at 20bb and deeper). */
const realization = (h, stack) => 1 - (1 - baseRealization(h)) * Math.min(1, (stack - OPEN) / 18);
const setup = (stack, hands) => ({ players: 9, stack, sb: 0.5, bb: 1, bbAnte: 1, open: OPEN, bbRealization: hands.map((h) => realization(h, stack)) });
const plain = (x) => (x instanceof Float64Array ? [...x] : x.map(plain));

if (!isMainThread && workerData?.shortNash) {
  const { solveOpenJam } = await load("src/poker/openjam.ts");
  const { ALL_HANDS } = await load("src/poker/cards.ts");
  const { eq, cnt, stack } = workerData;
  const t0 = Date.now();
  const sol = solveOpenJam({ eq, cnt }, setup(stack, ALL_HANDS), ITERATIONS);
  const { open, jam, callJam, reJam, bbCall, callReJam, exploitability } = sol;
  const fields = Object.fromEntries(Object.entries({ open, jam, callJam, reJam, bbCall, callReJam }).map(([k, v]) => [k, plain(v)]));
  parentPort.postMessage({ stack, seconds: (Date.now() - t0) / 1000, exploitability, ...fields });
} else if (isMainThread) {
  const { ALL_HANDS, comboCount } = await load("src/poker/cards.ts");
  const { rangeToString } = await load("src/poker/range.ts");
  const table = await loadEquityTable();

  // Solve the stacks in parallel, one worker per stack, at most one per CPU.
  const queue = [...STACKS];
  const results = [];
  await Promise.all(
    Array.from({ length: Math.min(cpus().length, STACKS.length) }, async () => {
      while (queue.length) {
        const stack = queue.shift();
        results.push(
          await new Promise((resolve, reject) => {
            const w = new Worker(new URL(import.meta.url), { workerData: { shortNash: true, eq: table.eq, cnt: table.cnt, stack } });
            w.once("message", resolve);
            w.once("error", reject);
          }),
        );
      }
    }),
  );
  results.sort((a, b) => a.stack - b.stack);

  const snap = (x) => (x < 0.1 ? 0 : x > 0.9 ? 1 : Math.round(x * 10) / 10);
  const toText = (f) => rangeToString(Object.fromEntries(ALL_HANDS.map((h, i) => [h, snap(f[i])])));
  const pct = (f) => (ALL_HANDS.reduce((s, h, i) => s + snap(f[i]) * comboCount(h), 0) / 13.26).toFixed(0);

  const stages = results.map((r) => {
    const st = { stack: r.stack, exploitability: Math.round(r.exploitability * 10000) / 10000, open: {}, jam: {}, reJam: {}, bbCall: {}, callReJam: {}, callJam: {} };
    for (let i = 0; i < 8; i++) {
      const op = SEATS[i];
      st.open[op] = toText(r.open[i]);
      st.jam[op] = toText(r.jam[i]);
      st.bbCall[op] = toText(r.bbCall[i]);
      for (let j = i + 1; j < 9; j++) {
        const c = SEATS[j];
        (st.reJam[c] ??= {})[op] = toText(r.reJam[i][j]);
        (st.callJam[c] ??= {})[op] = toText(r.callJam[i][j]);
        (st.callReJam[op] ??= {})[c] = toText(r.callReJam[i][j]);
      }
    }
    console.log(
      `${String(r.stack).padStart(2)}bb ${r.seconds.toFixed(0)}s exploit ${r.exploitability.toFixed(4)}  open/jam% ` +
        [0, 3, 5, 6, 7].map((i) => `${SEATS[i]} ${pct(r.open[i])}/${pct(r.jam[i])}`).join(" | ") +
        "  BB call/jam vs " +
        [0, 5, 6, 7].map((i) => `${SEATS[i]} ${pct(r.bbCall[i])}/${pct(r.reJam[i][8])}`).join(" | "),
    );
    return st;
  });

  const out = `// Generated by scripts/make-shortnash.mjs. Do not edit by hand; rerun the script instead.
// Chip-EV equilibrium for 9-handed short stacks with a 1bb BB ante: fold / ${OPEN}bb open / jam first in,
// re-jam or fold over an open (the BB may also flat), call or fold a jam. After a BB flat the hand is
// checked down and the BB realizes part of its equity by hand type (pairs and good suited hands 90%,
// offsuit broadways 85%, weak offsuit hands 55%; closer to 100% at short stacks). See
// src/poker/openjam.ts and scripts/make-shortnash.mjs.

export interface ShortNashStage {
  stack: number;
  exploitability: number;
  /** First in, per seat. */
  open: Record<string, string>;
  jam: Record<string, string>;
  /** reJam[me][opener]: 3-bet all-in over an open. */
  reJam: Record<string, Record<string, string>>;
  /** bbCall[opener]: the BB flats an open. */
  bbCall: Record<string, string>;
  /** callReJam[opener][reJammer]: the opener calls a re-jam. */
  callReJam: Record<string, Record<string, string>>;
  /** callJam[me][jammer]: call a first-in jam. */
  callJam: Record<string, Record<string, string>>;
}

export const SHORT_NASH_OPEN = ${OPEN};
export const SHORT_NASH_STAGES: ShortNashStage[] = ${JSON.stringify(stages, null, 1)};
`;
  writeFileSync(root + "src/data/sets/shortNashData.ts", out);
  console.log("wrote src/data/sets/shortNashData.ts");
}
